use anyhow::anyhow;
use argon2::{
    Algorithm, Argon2, Params, Version,
    password_hash::{PasswordHasher, PasswordVerifier, phc::PasswordHash},
};

use crate::config::Argon2Config;

/// Unambiguous alphabet (no 0/O, 1/I/L, U/V confusion): 30 symbols.
const ALPHABET: &[u8] = b"ABCDEFGHJKMNPQRSTVWXYZ23456789";
/// 12 symbols ≈ 59 bits of entropy. The first [`LOOKUP_LEN`] symbols are
/// stored in clear as an index (see [`lookup_key`]), which leaves ≈ 49 bits
/// behind the Argon2id hash — the margin the earlier 10-symbol codes had in
/// full.
const CODE_LEN: usize = 12;
/// Symbols of the normalized code stored alongside its hash, so a recovery
/// attempt verifies one candidate instead of every unused code.
pub const LOOKUP_LEN: usize = 2;

/// Argon2id hash of a recovery code plus its clear-text lookup prefix.
#[derive(Debug, Clone)]
pub struct HashedCode {
    pub hash: String,
    pub lookup: String,
}

/// Generate `count` one-time recovery codes, formatted `XXXX-XXXX-XXXX`.
pub fn generate_codes(count: u8) -> Vec<String> {
    (0..count).map(|_| generate_code()).collect()
}

fn generate_code() -> String {
    let mut symbols = Vec::with_capacity(CODE_LEN);
    while symbols.len() < CODE_LEN {
        for byte in crate::crypto::random_bytes::<16>() {
            // Rejection sampling: 240 = 8 * 30 keeps the distribution uniform.
            if byte < 240 {
                symbols.push(ALPHABET[(byte % 30) as usize]);
                if symbols.len() == CODE_LEN {
                    break;
                }
            }
        }
    }
    let text = String::from_utf8(symbols).expect("alphabet is ASCII");
    format!("{}-{}-{}", &text[..4], &text[4..8], &text[8..])
}

/// Canonical form used for hashing and verification: uppercase, alphanumerics
/// only (so users may type codes with or without the dash).
pub fn normalize(code: &str) -> String {
    code.chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .map(|c| c.to_ascii_uppercase())
        .collect()
}

/// Clear-text index key for a code: its first [`LOOKUP_LEN`] normalized
/// symbols (uppercase, separators removed), so users may type the code in any
/// casing or grouping.
pub fn lookup_key(code: &str) -> String {
    normalize(code).chars().take(LOOKUP_LEN).collect()
}

/// Argon2id hasher for recovery codes.
pub struct RecoveryHasher {
    argon2: Argon2<'static>,
}

impl RecoveryHasher {
    pub fn new(cfg: &Argon2Config) -> anyhow::Result<Self> {
        let params = Params::new(cfg.memory_kib, cfg.iterations, cfg.parallelism, None)
            .map_err(|e| anyhow!("invalid argon2 parameters: {e}"))?;
        Ok(Self {
            argon2: Argon2::new(Algorithm::Argon2id, Version::V0x13, params),
        })
    }

    pub fn hash(&self, code: &str) -> anyhow::Result<String> {
        // A fresh random salt is generated by the hasher.
        let hash = self
            .argon2
            .hash_password(normalize(code).as_bytes())
            .map_err(|e| anyhow!("argon2 hashing failed: {e}"))?;
        Ok(hash.to_string())
    }

    pub fn verify(&self, code: &str, phc: &str) -> bool {
        let Ok(parsed) = PasswordHash::new(phc) else {
            return false;
        };
        self.argon2
            .verify_password(normalize(code).as_bytes(), &parsed)
            .is_ok()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fast_hasher() -> RecoveryHasher {
        RecoveryHasher::new(&Argon2Config {
            memory_kib: 8,
            iterations: 1,
            parallelism: 1,
            ..Argon2Config::default()
        })
        .unwrap()
    }

    #[test]
    fn codes_have_expected_shape_and_are_unique() {
        let codes = generate_codes(20);
        assert_eq!(codes.len(), 20);
        for code in &codes {
            assert_eq!(code.len(), 14);
            assert_eq!(code.as_bytes()[4], b'-');
            assert_eq!(code.as_bytes()[9], b'-');
            assert!(normalize(code).bytes().all(|b| ALPHABET.contains(&b)));
            assert_eq!(lookup_key(code).len(), LOOKUP_LEN);
            assert!(code.starts_with(&lookup_key(code)));
        }
        let unique: std::collections::HashSet<_> = codes.iter().collect();
        assert_eq!(unique.len(), codes.len());
    }

    #[test]
    fn lookup_key_is_normalized() {
        assert_eq!(lookup_key("ab-cd-ef"), "AB");
        assert_eq!(lookup_key(" k9 "), "K9");
        assert_eq!(lookup_key("-"), "");
    }

    #[test]
    fn hash_verify_roundtrip_and_normalization() {
        let hasher = fast_hasher();
        let code = generate_code();
        let phc = hasher.hash(&code).unwrap();

        assert!(hasher.verify(&code, &phc));
        assert!(hasher.verify(&code.to_lowercase(), &phc));
        assert!(hasher.verify(&code.replace('-', " "), &phc));
        assert!(!hasher.verify("AAAAA-AAAAA", &phc));
        assert!(!hasher.verify(&code, "not-a-phc-string"));
    }
}
